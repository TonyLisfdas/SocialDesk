export const DICTS = { zh, en };

export interface I18n {
  lang: Lang;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
  setLang: (l: Lang) => void;
}

export const I18nContext = createContext<I18n>({
  lang: 'zh',
  t: (k) => zh[k] ?? String(k),
  setLang: () => {},
});

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang] ?? zh;
  let out: string = (dict as Record<string, string>)[key] ?? (zh as Record<string, string>)[key] ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return out;
}
